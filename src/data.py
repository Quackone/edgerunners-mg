def _parse_srt(path):
    raw = open(path, encoding="utf-8").read().strip().replace("\r", "")
    out = []
    for blk in re.split(r"\n\s*\n", raw):
        ls = [l for l in blk.split("\n") if l.strip()]
        if len(ls) < 3:
            continue
        m = re.match(r"(\d\d):(\d\d):(\d\d),(\d\d\d)\s*-->\s*(\d\d):(\d\d):(\d\d),(\d\d\d)", ls[1])
        if not m:
            continue
        g = list(map(int, m.groups()))
        t0 = g[0] * 3600 + g[1] * 60 + g[2] + g[3] / 1000
        t1 = g[4] * 3600 + g[5] * 60 + g[6] + g[7] / 1000
        out.append({"t0": t0, "t1": t1, "text": "".join(ls[2:])})
    for i, c in enumerate(out):
        c["i"] = i + 1
    return out


